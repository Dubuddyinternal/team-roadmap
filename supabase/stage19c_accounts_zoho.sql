-- =====================================================================
-- STAGE 19c — Accounts → Zoho Books
--
-- What a payment needs for the books, and where the Zoho sync keeps track:
--   · acc_requests: a stable number (TOOLS-<ref_no>), TDS, GST bill,
--     "paid from" account, advances, and zoho_ids / zoho_status / zoho_error
--   · acc_payroll: TDS per person; acc_payroll_runs: one Zoho journal a month
--   · acc_zoho_settings: Zoho account and tax ids, fetched once by name
--   · acc_zoho_log: every Zoho request and response (no tokens)
-- The posting itself is done by the Edge Function "zoho-sync".
-- Run after stage19b. Safe to run again.
-- =====================================================================

alter table public.acc_requests add column if not exists ref_no bigint generated by default as identity;
create unique index if not exists acc_requests_ref_no on public.acc_requests (ref_no);
alter table public.acc_requests drop constraint if exists acc_requests_kind_check;
alter table public.acc_requests add constraint acc_requests_kind_check check (kind in ('reimbursement', 'vendor', 'advance'));
alter table public.acc_requests add column if not exists tds_percent numeric(5,2) not null default 0 check (tds_percent between 0 and 50);
alter table public.acc_requests add column if not exists tds_amount numeric(12,2) not null default 0 check (tds_amount >= 0);
alter table public.acc_requests add column if not exists tds_section text not null default '' check (length(tds_section) <= 10);
alter table public.acc_requests add column if not exists has_gst_bill boolean not null default false;
alter table public.acc_requests add column if not exists vendor_gstin text not null default '' check (length(vendor_gstin) <= 15);
alter table public.acc_requests add column if not exists gst_amount numeric(12,2) not null default 0 check (gst_amount >= 0);
alter table public.acc_requests add column if not exists paid_from text not null default 'Punjab National Bank' check (length(paid_from) <= 80);
alter table public.acc_requests add column if not exists imprest_account text not null default '' check (length(imprest_account) <= 80);
alter table public.acc_requests add column if not exists source text not null default 'tools';
alter table public.acc_requests add column if not exists zoho_ids jsonb not null default '{}'::jsonb;
alter table public.acc_requests add column if not exists zoho_status text not null default 'none'
  check (zoho_status in ('none', 'pending', 'synced', 'failed', 'dry_run', 'manual'));
alter table public.acc_requests add column if not exists zoho_error text;
alter table public.acc_requests add column if not exists zoho_synced_at timestamptz;

alter table public.acc_payroll add column if not exists tds numeric(12,2) not null default 0 check (tds >= 0);

create table if not exists public.acc_payroll_runs (
  month          text primary key check (month ~ '^\d{4}-\d{2}$'),
  paid_on        date,
  paid_ref       text,
  paid_from      text not null default 'Punjab National Bank',
  warning        text,
  zoho_ids       jsonb not null default '{}'::jsonb,
  zoho_status    text not null default 'none' check (zoho_status in ('none', 'pending', 'synced', 'failed', 'dry_run')),
  zoho_error     text,
  zoho_synced_at timestamptz
);
alter table public.acc_payroll_runs enable row level security;
create policy "accounts read runs" on public.acc_payroll_runs for select to authenticated using (public.acc_can());

create table if not exists public.acc_zoho_settings (
  id         int primary key default 1 check (id = 1),
  accounts   jsonb not null default '{}'::jsonb,   -- exact Zoho account name -> account_id
  taxes      jsonb not null default '{}'::jsonb,   -- IGST18 / GST18 -> tax_id
  missing    text[] not null default '{}',
  fetched_at timestamptz
);
insert into public.acc_zoho_settings (id) values (1) on conflict (id) do nothing;
alter table public.acc_zoho_settings enable row level security;
create policy "accounts read zoho settings" on public.acc_zoho_settings for select to authenticated using (public.acc_can());

create table if not exists public.acc_zoho_log (
  id       bigint generated always as identity primary key,
  at       timestamptz not null default now(),
  action   text, ref text, method text, path text,
  request  jsonb, response jsonb, http int, ok boolean, dry boolean
);
create index if not exists acc_zoho_log_at on public.acc_zoho_log (at desc);
alter table public.acc_zoho_log enable row level security;
create policy "accounts read zoho log" on public.acc_zoho_log for select to authenticated using (public.acc_can());

revoke all on public.acc_payroll_runs, public.acc_zoho_settings, public.acc_zoho_log from anon;
grant select on public.acc_payroll_runs, public.acc_zoho_settings, public.acc_zoho_log to authenticated;

-- ---------- functions ----------
-- ask: now with GST bill details, and advances
create or replace function public.acc_request_create(p jsonb)
returns public.acc_requests language plpgsql security definer set search_path = '' as $$
declare me uuid := auth.uid(); r public.acc_requests; k text := p->>'kind'; amt numeric; gst text := upper(coalesce(trim(p->>'vendor_gstin'), ''));
begin
  if me is null or not exists (select 1 from public.memberships m where m.user_id = me) then raise exception 'Please sign in.'; end if;
  if k not in ('reimbursement', 'vendor', 'advance') then raise exception 'Pick what kind of payment it is.'; end if;
  begin amt := round((p->>'amount')::numeric, 2); exception when others then raise exception 'Enter the amount.'; end;
  if amt is null or amt <= 0 then raise exception 'Enter the amount.'; end if;
  if length(trim(coalesce(p->>'title', ''))) < 2 then raise exception 'Say what it''s for.'; end if;
  if k = 'vendor' and (length(trim(coalesce(p->>'payee_name', ''))) < 2
       or (coalesce(trim(p->>'payee_upi'), '') = '' and (coalesce(trim(p->>'payee_account'), '') = '' or coalesce(trim(p->>'payee_ifsc'), '') = ''))) then
    raise exception 'Add who to pay, and their UPI ID or bank account and IFSC.';
  end if;
  if coalesce((p->>'has_gst_bill')::boolean, false) and gst !~ '^\d{2}[A-Z0-9]{13}$' then raise exception 'Enter the seller''s 15-character GSTIN.'; end if;
  insert into public.acc_requests (user_id, kind, title, amount, category, spent_on, notes, payee_name, payee_upi, payee_account, payee_ifsc, payee_bank, payee_pan,
                                   has_gst_bill, vendor_gstin)
  values (me, k, left(trim(p->>'title'), 160), amt, left(coalesce(p->>'category', ''), 60), nullif(p->>'spent_on', '')::date,
          left(coalesce(p->>'notes', ''), 2000), left(coalesce(trim(p->>'payee_name'), ''), 140), left(coalesce(trim(p->>'payee_upi'), ''), 100),
          left(regexp_replace(coalesce(p->>'payee_account', ''), '\s', '', 'g'), 40), left(upper(coalesce(trim(p->>'payee_ifsc'), '')), 20),
          left(coalesce(trim(p->>'payee_bank'), ''), 100), left(upper(coalesce(trim(p->>'payee_pan'), '')), 20),
          coalesce((p->>'has_gst_bill')::boolean, false), case when coalesce((p->>'has_gst_bill')::boolean, false) then gst else '' end)
  returning * into r;
  perform public.hr_bell(array(select unnest(public.acc_people()) except select me),
    '💰 ' || public.hr_name(me) || ' asked for ₹' || to_char(amt, 'FM99,99,99,990.00') || ': ' || r.title,
    case k when 'vendor' then 'Vendor payment to ' || r.payee_name when 'advance' then 'Advance' else 'Reimbursement' end
      || E'.\n\nApprove it in Administration → Accounts → Payment requests.',
    public.hr_team_of(me));
  return r;
end $$;

-- Accounts sets the bookkeeping details before paying
create or replace function public.acc_request_edit(p_id uuid, p jsonb)
returns public.acc_requests language plpgsql security definer set search_path = '' as $$
declare r public.acc_requests; pct numeric; gst text := upper(coalesce(trim(p->>'vendor_gstin'), ''));
begin
  if not public.acc_can() then raise exception 'You need the “Accounts: payments & payroll” permission.'; end if;
  pct := least(greatest(coalesce(nullif(p->>'tds_percent', '')::numeric, 0), 0), 50);
  if coalesce((p->>'has_gst_bill')::boolean, false) and gst !~ '^\d{2}[A-Z0-9]{13}$' then raise exception 'Enter the seller''s 15-character GSTIN.'; end if;
  update public.acc_requests
     set category = left(coalesce(p->>'category', category), 60),
         tds_percent = pct, tds_amount = round(amount * pct / 100, 0), tds_section = left(coalesce(p->>'tds_section', ''), 10),
         has_gst_bill = coalesce((p->>'has_gst_bill')::boolean, false),
         vendor_gstin = case when coalesce((p->>'has_gst_bill')::boolean, false) then gst else '' end,
         gst_amount = coalesce(nullif(p->>'gst_amount', '')::numeric, 0),
         spent_on = coalesce(nullif(p->>'spent_on', '')::date, spent_on),
         imprest_account = left(coalesce(p->>'imprest_account', imprest_account), 80)
   where id = p_id and status in ('pending', 'approved') returning * into r;
  if r.id is null then raise exception 'A paid request can''t be changed.'; end if;
  return r;
end $$;

-- mark paid (net of TDS) from a chosen account; the Zoho sync picks it up
create or replace function public.acc_pay(p_ids uuid[], p_date date, p_ref text, p_paid_from text default 'Punjab National Bank')
returns int language plpgsql security definer set search_path = '' as $$
declare r public.acc_requests; n int := 0;
begin
  if not public.acc_can() then raise exception 'You need the “Accounts: payments & payroll” permission.'; end if;
  for r in update public.acc_requests set status = 'paid', paid_at = coalesce(p_date, current_date), paid_ref = nullif(left(trim(coalesce(p_ref, '')), 120), ''),
                  paid_by = auth.uid(), paid_from = coalesce(nullif(trim(p_paid_from), ''), 'Punjab National Bank'), zoho_status = 'pending', zoho_error = null
            where id = any(p_ids) and status = 'approved' returning * loop
    n := n + 1;
    perform public.hr_bell(array[r.user_id], '💸 Paid: ' || r.title || ' (₹' || to_char(r.amount - r.tds_amount, 'FM99,99,99,990.00') || ')',
      'Paid on ' || to_char(r.paid_at, 'DD Mon YYYY') || coalesce(' · Ref ' || r.paid_ref, '')
        || case when r.tds_amount > 0 then ' · TDS ₹' || to_char(r.tds_amount, 'FM99,99,99,990') || ' deducted' else '' end
        || E'.\n\nSee it in Administration → For me → My payments.');
  end loop;
  return n;
end $$;

-- payroll row with TDS
create or replace function public.acc_payroll_save2(p_id uuid, p_base numeric, p_bonus numeric, p_reimb numeric, p_deductions numeric, p_tds numeric, p_note text)
returns public.acc_payroll language plpgsql security definer set search_path = '' as $$
declare r public.acc_payroll;
begin
  if not public.acc_can() then raise exception 'You need the “Accounts: payments & payroll” permission.'; end if;
  update public.acc_payroll set base = greatest(coalesce(p_base, 0), 0), bonus = greatest(coalesce(p_bonus, 0), 0), reimb = greatest(coalesce(p_reimb, 0), 0),
         deductions = greatest(coalesce(p_deductions, 0), 0), tds = greatest(coalesce(p_tds, 0), 0), note = left(coalesce(p_note, ''), 500), updated_at = now(), updated_by = auth.uid()
   where id = p_id and status = 'draft' returning * into r;
  if r.id is null then raise exception 'Only a draft salary can be changed.'; end if;
  return r;
end $$;

-- statuses; paying a month also records the run for Zoho (one journal) and
-- queues the reimbursements paid with it
create or replace function public.acc_payroll_status(p_ids uuid[], p_status text, p_date date default null, p_ref text default null)
returns int language plpgsql security definer set search_path = '' as $$
declare r public.acc_payroll; n int := 0; m text; mon text; pd date := coalesce(p_date, current_date);
begin
  if not public.acc_can() then raise exception 'You need the “Accounts: payments & payroll” permission.'; end if;
  if p_status = 'approved' then
    update public.acc_payroll set status = 'approved', updated_at = now(), updated_by = auth.uid() where id = any(p_ids) and status = 'draft';
    get diagnostics n = row_count;
  elsif p_status = 'draft' then
    update public.acc_payroll set status = 'draft', updated_at = now(), updated_by = auth.uid() where id = any(p_ids) and status = 'approved';
    get diagnostics n = row_count;
  elsif p_status = 'paid' then
    for r in update public.acc_payroll set status = 'paid', paid_at = pd, paid_ref = nullif(left(trim(coalesce(p_ref, '')), 120), ''),
                    updated_at = now(), updated_by = auth.uid()
              where id = any(p_ids) and status = 'approved' returning * loop
      n := n + 1; mon := r.month;
      m := to_char(to_date(r.month || '-01', 'YYYY-MM-DD'), 'FMMonth YYYY');
      if r.reimb > 0 then
        update public.acc_requests set status = 'paid', paid_at = r.paid_at, paid_ref = coalesce(r.paid_ref, 'With ' || m || ' salary'), paid_by = auth.uid(),
               paid_from = 'Punjab National Bank', zoho_status = 'pending', zoho_error = null
         where user_id = r.user_id and kind = 'reimbursement' and status = 'approved';
      end if;
      perform public.hr_bell(array[r.user_id], '💸 Your ' || m || ' salary is paid',
        '₹' || to_char(r.base + r.bonus + r.reimb - r.deductions - r.tds, 'FM99,99,99,990.00') || ' on ' || to_char(r.paid_at, 'DD Mon YYYY')
          || coalesce(' · Ref ' || r.paid_ref, '') || case when r.tds > 0 then ' · TDS ₹' || to_char(r.tds, 'FM99,99,99,990') || ' deducted' else '' end || '.');
    end loop;
    if mon is not null then
      insert into public.acc_payroll_runs (month, paid_on, paid_ref, warning, zoho_status)
      values (mon, pd, nullif(trim(coalesce(p_ref, '')), ''),
              case when right(mon, 2) = '03' and pd >= make_date(left(mon, 4)::int, 4, 1) then 'Paid after 31 March — tell the CA (it may need a provision).' end, 'pending')
      on conflict (month) do update set paid_on = excluded.paid_on, paid_ref = coalesce(excluded.paid_ref, public.acc_payroll_runs.paid_ref),
             warning = excluded.warning, zoho_status = 'pending', zoho_error = null;
    end if;
  else
    raise exception 'Unknown status.';
  end if;
  return n;
end $$;

revoke execute on function public.acc_request_edit(uuid, jsonb), public.acc_pay(uuid[], date, text, text),
  public.acc_payroll_save2(uuid, numeric, numeric, numeric, numeric, numeric, text) from public, anon;
grant execute on function public.acc_request_edit(uuid, jsonb), public.acc_pay(uuid[], date, text, text),
  public.acc_payroll_save2(uuid, numeric, numeric, numeric, numeric, numeric, text) to authenticated;
